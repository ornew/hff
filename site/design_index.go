package main

import "github.com/ornew/nanosite/render"

// Record metadata and index text are project policy; Nanosite generates and
// validates the table for both the site and checked-in index command.
func designIndexMarkdown(repo string) ([]byte, error) {
	return render.RecordIndexMarkdown(repo, render.RecordIndex{
		Directory: "docs/design", Heading: "Introduction",
		Introduction:    "These documents explain the rationale, contracts, and tradeoffs behind HFF's language design. The language specification defines the query language; records provide context for individual design choices.",
		GeneratedNotice: "Generated by hack/generate-design-index.sh. Do not edit.",
		Columns:         []render.Column{{Title: "Record", Field: "Title"}, {Title: "Status", Field: "Status"}, {Title: "Date", Field: "Date"}, {Title: "Author", Field: "Author"}},
		Required:        []string{"Status", "Date", "Author"}, Template: "000-template.md",
		TemplateText: "Use the [record template](000-template.md) when adding a design record.",
	})
}
func designTableText(s string) string { return render.TableText(s) }
