package main

import (
	"bytes"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/ast"
	"github.com/yuin/goldmark/text"
)

var designRecordName = regexp.MustCompile(`^([0-9]{3})-.+\.md$`)
var designMetadata = regexp.MustCompile(`^\*\*(Status|Date|Author)\*\*:[ \t]*(.*?)[ \t]*\r?$`)

// designIndexMarkdown is shared by the site and the checked-in Markdown index.
// The site's introduction is generated even when the checked-in copy is stale.
func designIndexMarkdown(repo string) ([]byte, error) {
	dir := filepath.Join(repo, "docs", "design")
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("<!-- Generated by hack/generate-design-index.sh. Do not edit. -->\n\n# Introduction\n\n")
	out.WriteString("These documents explain the rationale, contracts, and tradeoffs behind HFF's language design. The language specification defines the query language; records provide context for individual design choices.\n\n")
	out.WriteString("| Record | Status | Date | Author |\n| --- | --- | --- | --- |\n")
	ids := map[string]string{}
	md := goldmark.New()
	template := false
	for _, entry := range entries { // ReadDir returns entries sorted by filename.
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if name == "000-template.md" {
			template = true
		}
		match := designRecordName.FindStringSubmatch(name)
		if match == nil || match[1] == "000" {
			continue
		}
		if previous, exists := ids[match[1]]; exists {
			return nil, fmt.Errorf("docs/design: duplicate record number %s in %s and %s", match[1], previous, name)
		}
		ids[match[1]] = name
		src, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		var title string
		doc := md.Parser().Parse(text.NewReader(src))
		for n := doc.FirstChild(); n != nil; n = n.NextSibling() {
			if h, ok := n.(*ast.Heading); ok && h.Level == 1 {
				title = strings.TrimSpace(string(h.Text(src)))
				break
			}
		}
		if title == "" {
			return nil, fmt.Errorf("docs/design/%s: missing level-one title", name)
		}
		metadata := map[string]string{}
		// Inspect actual top-level list items, not examples inside code blocks
		// or quoted content that happens to contain metadata-looking text.
		for n := doc.FirstChild(); n != nil; n = n.NextSibling() {
			if _, ok := n.(*ast.List); !ok {
				continue
			}
			for item := n.FirstChild(); item != nil; item = item.NextSibling() {
				block := item.FirstChild()
				if block == nil || block.Lines().Len() != 1 {
					continue
				}
				match := designMetadata.FindSubmatch(bytes.TrimSpace(block.Lines().Value(src)))
				if match == nil {
					continue
				}
				key, value := string(match[1]), strings.TrimSpace(string(match[2]))
				if _, exists := metadata[key]; exists {
					return nil, fmt.Errorf("docs/design/%s: duplicate %s metadata", name, key)
				}
				metadata[key] = value
			}
		}
		for _, key := range []string{"Status", "Date", "Author"} {
			if metadata[key] == "" {
				return nil, fmt.Errorf("docs/design/%s: missing %s metadata", name, key)
			}
		}
		fmt.Fprintf(&out, "| [%s](%s) | %s | %s | %s |\n", designTableText(title),
			url.PathEscape(name), designTableText(metadata["Status"]),
			designTableText(metadata["Date"]), designTableText(metadata["Author"]))
	}
	if template {
		out.WriteString("\nUse the [record template](000-template.md) when adding a design record.\n")
	}
	return out.Bytes(), nil
}

// Escape Markdown punctuation so titles and metadata are displayed as text,
// including pipes, link syntax, and HTML. Newlines cannot create extra rows.
func designTableText(s string) string {
	var out strings.Builder
	for _, r := range s {
		if r == '\n' || r == '\r' {
			out.WriteByte(' ')
			continue
		}
		if strings.ContainsRune("!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~", r) {
			out.WriteByte('\\')
		}
		out.WriteRune(r)
	}
	return out.String()
}
