package main

import (
	"fmt"
	"html/template"
	"path/filepath"

	"github.com/ornew/nanosite/sitegen"
)

func (s navSection) FirstPage() *page {
	if len(s.Pages) > 0 {
		return s.Pages[0]
	}
	for _, child := range s.Children {
		if p := child.FirstPage(); p != nil {
			return p
		}
	}
	return nil
}

func build(repo, out string) (int, error) {
	c, err := sitegen.ReadConfig(filepath.Join(repo, "site/config.json"))
	if err != nil {
		return 0, err
	}
	mapped := map[*sitegen.Page]*page{}
	var themePages []*page
	extensions := sitegen.Extensions{
		Marker: ".hff-site", MarkerContent: []byte("Generated by HFF site\n"),
		Protected: []string{"README.md", "docs", "spec", "site", "playground", ".git"}, AllowedOutput: []string{"site/dist"},
		TemplateFuncs: template.FuncMap{"rel": relative},
		Prepare: func(ctx *sitegen.Context) error {
			if err := addGoReference(ctx); err != nil {
				return err
			}
			for _, source := range ctx.Pages {
				p := &page{Source: source.Source, URL: source.Output, Title: source.Title, NavTitle: source.NavTitle, NoSource: source.NoSource, doc: source.Document, src: source.Body, anchors: source.Anchors, Home: source.Source == "README.md", Playground: source.Source == "docs/playground.md"}
				for _, h := range source.Headings {
					if h.Level == 1 && p.HomeAnchor == "" {
						p.HomeAnchor = h.ID
					}
					if h.Level >= 2 && h.Level <= 3 {
						p.Headings = append(p.Headings, heading{h.ID, h.Title})
					}
				}
				mapped[source] = p
				themePages = append(themePages, p)
				source.Data = p
				if p.Playground {
					files, err := compilePlayground(repo)
					if err != nil {
						return err
					}
					for name, data := range files {
						ctx.Assets[name] = data
					}
				}
			}
			return nil
		},
		Decorate: func(ctx *sitegen.Context, source *sitegen.Page, body string) (string, error) {
			p := mapped[source]
			p.Body = template.HTML(body)
			if p.Home {
				if err := prepareLanding(ctx.Markdown, p); err != nil {
					return "", err
				}
			}
			if p.Home {
				plain := p.Intro + " " + p.Example + " " + sitegen.HTMLText(string(p.Body))
				for _, feature := range p.Features {
					plain += " " + feature.ID + " " + feature.Title
				}
				source.SearchText = &plain
			}
			return string(p.Body), nil
		},
		View: func(v sitegen.View) (any, error) {
			p := mapped[v.Page]
			if p == nil {
				return nil, fmt.Errorf("missing theme data")
			}
			var convert func([]sitegen.NavGroup) []navSection
			convert = func(groups []sitegen.NavGroup) []navSection {
				var result []navSection
				for _, g := range groups {
					s := navSection{Name: g.Title, Collapsible: g.Collapsed, Active: g.Active}
					for _, q := range g.Pages {
						s.Pages = append(s.Pages, mapped[q])
					}
					s.Children = convert(g.Children)
					result = append(result, s)
				}
				return result
			}
			data := view{Current: p, Sections: convert(v.Groups), Root: relative(p.URL, "index.html"), Prev: mapped[v.Previous], Next: mapped[v.Next]}
			// Only special page identification is site-specific; Nanosite supplies navigation and paging.
			for _, q := range themePages {
				data.Pages = append(data.Pages, q)
			}
			return data, nil
		},
	}
	result, err := sitegen.BuildWith(repo, out, c, false, extensions)
	if err != nil {
		return 0, err
	}
	return len(result.Pages), nil
}
